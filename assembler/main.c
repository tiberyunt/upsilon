/* Standalone native assembler, source-IR linker and ROM build utilities. */
#include "assembler.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>
#include <errno.h>
static void usage(void){
 puts("Upsilon native assembler and source-IR linker\n"
      "  upsilon-as source.s -o output.bin [--origin n] [--map file]\n"
      "  upsilon-as -c source.s -o output.obj [--origin n]\n"
      "  upsilon-ld input.obj|input.s [...] -o output.bin [--origin n] [--map file]\n"
      "  upsilon-as rom-link monitor.s basic.s native.s -o linked.s\n"
      "  upsilon-as embed input.bin -o firmware_image.h\n"
      "Objects use native UOBJ1 source IR, not ELF. GNU ELF tools are a separate port.");
}
static uint64_t number(const char *s){
 char *end;errno=0;unsigned long long n=strtoull(s,&end,0);
 if(errno||!*s||*end||*s=='-'){fprintf(stderr,"invalid origin: %s\n",s);exit(2);}return n;
}
static uint64_t get64(const unsigned char *p){uint64_t n=0;for(int i=7;i>=0;i--)n=(n<<8)|p[i];return n;}
static void put64(unsigned char *p,uint64_t n){for(int i=0;i<8;i++){p[i]=(unsigned char)n;n>>=8;}}
/* The IR retains extern declarations. Only the preview uses placeholder values;
 * final linking strips declarations and resolves real definitions together. */
static char *externs(const char *src,int preview,int *entries){
 size_t length=strlen(src),used=0;char *out=malloc(length*4+1024);
 if(!out)return NULL;
 for(const char *p=src;*p;){
  const char *end=strchr(p,'\n');if(!end)end=p+strlen(p);
  const char *s=p;while(s<end&&isspace((unsigned char)*s))s++;
  if(end-s>=6&&!strncmp(s,".entry",6)&&(end-s==6||isspace((unsigned char)s[6])))if(entries)(*entries)++;
  if(end-s>=7&&!strncmp(s,".extern",7)&&(end-s==7||isspace((unsigned char)s[7]))){
   s+=7;int names=0;
   while(s<end&&*s!=';'){
    while(s<end&&(isspace((unsigned char)*s)||*s==','))s++;
    if(s==end||*s==';')break;
    const char *name=s;while(s<end&&(isalnum((unsigned char)*s)||*s=='_'))s++;
    if(s==name){free(out);return NULL;}names++;
    if(preview){memcpy(out+used,".equ ",5);used+=5;memcpy(out+used,name,(size_t)(s-name));used+=(size_t)(s-name);memcpy(out+used,",0\n",3);used+=3;}
   }
   if(!names){free(out);return NULL;}
  }else{memcpy(out+used,p,(size_t)(end-p));used+=(size_t)(end-p);out[used++]='\n';}
  p=*end?end+1:end;
 }
 out[used]=0;return out;
}
static int map(const char *path,const Program *p){
 if(!path)return 1;FILE *f=fopen(path,"w");if(!f)return 0;
 fprintf(f,"{\"origin\":%llu,\"entry\":%llu,\"symbols\":{",(unsigned long long)p->origin,(unsigned long long)p->entry);
 for(size_t i=0;i<p->nsymbols;i++)fprintf(f,"%s\"%s\":%llu",i?",":"",p->symbols[i].name,(unsigned long long)p->symbols[i].value);
 fputs("}}\n",f);int ok=!ferror(f);if(fclose(f))ok=0;return ok;
}
int main(int argc,char **argv){
 const char *name=strrchr(argv[0],'/');name=name?name+1:argv[0];
 int linking=strstr(name,"upsilon-ld")!=NULL,object=0,start=1;
 const char *command=linking?"link":"asm",*output=NULL,*mapfile=NULL,*files[64];int count=0;
 uint64_t origin=4096;
 if(argc==2&&(!strcmp(argv[1],"--help")||!strcmp(argv[1],"-h"))){usage();return 0;}
 if(argc==2&&!strcmp(argv[1],"--version")){puts("Upsilon 0.4 native assembler/linker");return 0;}
 if(argc>1&&(!strcmp(argv[1],"asm")||!strcmp(argv[1],"link")||!strcmp(argv[1],"rom-link")||!strcmp(argv[1],"embed"))){command=argv[1];start=2;}
 linking=!strcmp(command,"link");
 for(int i=start;i<argc;i++){
  const char *arg=argv[i];
  if(!strcmp(arg,"-c")){object=1;continue;}
  if(!strcmp(arg,"-o")||!strcmp(arg,"--output")||!strcmp(arg,"--map")||!strcmp(arg,"--origin")){
   if(i+1==argc){usage();return 2;}const char *v=argv[++i];
   if(!strcmp(arg,"--origin"))origin=number(v);else if(!strcmp(arg,"--map"))mapfile=v;else output=v;
  }else if(*arg=='-'||count==64){usage();return 2;}else files[count++]=arg;
 }
 if(!count||!output||(object&&linking)||(!linking&&strcmp(command,"rom-link")&&count!=1)){usage();return 2;}
 if(!strcmp(command,"embed")){
  size_t n;char *p=readfile(files[0],&n);if(!p){perror(files[0]);return 1;}
  FILE *f=fopen(output,"w");if(!f){perror(output);free(p);return 1;}
  fputs("/* Built-in ROM generated by upsilon-as. */\nstatic const uint8_t upsilon_firmware_image[]={\n",f);
  for(size_t i=0;i<n;i++)fprintf(f,"%s0x%02x,%s",i%16==0?"    ":"",(unsigned char)p[i],i%16==15?"\n":"");
  fputs("\n};\n",f);int ok=!ferror(f);if(fclose(f))ok=0;free(p);return ok?0:1;
 }
 if(!strcmp(command,"rom-link")){
  if(count!=3){usage();return 2;}
  char *a=sourcefile(files[0],0),*b=sourcefile(files[1],0),*c=sourcefile(files[2],0),*out=NULL;
  int ok=a&&b&&c&&compose_rom(a,b,c,&out)&&writefile(output,out,strlen(out));free(a);free(b);free(c);free(out);
  if(!ok)fprintf(stderr,"could not compose ROM sources\n");return ok?0:1;
 }
 char *source=NULL;size_t used=0;int entries=0;
 for(int i=0;i<count;i++){
  size_t n;char *raw=readfile(files[i],&n),*text=NULL;
  if(!raw){perror(files[i]);free(source);return 1;}
  if(linking&&n>=5&&!memcmp(raw,"UOBJ1",5)){
   if(n<32||memcmp(raw,"UOBJ1\0\0\0",8)||get64((unsigned char *)raw+8)>n-32||get64((unsigned char *)raw+16)!=n-32-get64((unsigned char *)raw+8)){
    fprintf(stderr,"invalid UOBJ1 object: %s\n",files[i]);free(raw);free(source);return 1;
   }
   size_t size=(size_t)get64((unsigned char *)raw+8);
   if(memchr(raw+32,0,size)){fprintf(stderr,"NUL in object IR\n");free(raw);free(source);return 1;}
   text=malloc(size+1);if(text){memcpy(text,raw+32,size);text[size]=0;}
  }else if(!memchr(raw,0,n))text=sourcefile(files[i],0);
  free(raw);
  if(!text){fprintf(stderr,"invalid assembly input: %s\n",files[i]);free(source);return 1;}
  char *resolved=linking?externs(text,0,&entries):NULL;
  if(linking&&!resolved){fprintf(stderr,"invalid extern declaration\n");free(text);free(source);return 1;}
  const char *part=linking?resolved:text;size_t size=strlen(part);
  char *next=realloc(source,used+size+2);if(!next){free(text);free(resolved);free(source);return 1;}
  source=next;memcpy(source+used,part,size);used+=size;source[used++]='\n';source[used]=0;free(text);free(resolved);
 }
 if(linking&&entries>1){fprintf(stderr,"multiple .entry directives\n");free(source);return 1;}
 char *preview=object?externs(source,1,NULL):NULL;
 if(object&&!preview){fprintf(stderr,"invalid extern declaration\n");free(source);return 1;}
 Program p;int ok=assemble(object?preview:source,origin,0,&p);free(preview);
 if(!ok){fprintf(stderr,"upsilon-as: %s\n",p.error);free(source);free_program(&p);return 1;}
 if(object){
  size_t size=strlen(source),length=32+size+p.length;unsigned char *bytes=malloc(length);
  if(!bytes)ok=0;else{memcpy(bytes,"UOBJ1\0\0\0",8);put64(bytes+8,size);put64(bytes+16,p.length);put64(bytes+24,p.entry);memcpy(bytes+32,source,size);memcpy(bytes+32+size,p.data,p.length);ok=writefile(output,bytes,length);free(bytes);}
 }else ok=writefile(output,p.data,p.length);
 if(ok)ok=map(mapfile,&p);
 if(ok)printf("%zu bytes at 0x%llx; entry 0x%llx\n",p.length,(unsigned long long)p.origin,(unsigned long long)p.entry);
 else perror(output);
 free(source);free_program(&p);return ok?0:1;
}
